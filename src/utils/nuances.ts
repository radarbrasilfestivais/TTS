// Helper to wrap text with tags
export function wrapWithNuanceTag(
  selectedText: string,
  nuance: NuanceType,
  pauseSec: number = 1.0
): string {
  if (nuance === 'pause') {
    return `[pausa: ${pauseSec}s]`;
  }
  const preset = NUANCE_PRESETS[nuance];
  const tag = preset.tag;
  return `[${tag}]${selectedText || 'insira o texto aqui'}[/${tag}]`;
}

// Remove nuance tags for plain text export
export function stripNuanceTags(rawText: string): string {
  return rawText
    .replace(/\[\/?(sussurro|whisper|sussurrando|forte|strong|loud|enfase|ênfase|emphasis|calmo|calm|suave|alegre|excited|animado|dramatico|dramático|dramatic|rapido|rápido|fast|robo|robô|robotic)\]/gi, '')
    .replace(/\[pausa:?\s*(\d+(\.\d+)?)s?\]/gi, ' ... ')
    .trim();
}
